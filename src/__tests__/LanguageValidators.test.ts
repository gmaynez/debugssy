describe('Language-specific danger coverage', () => {
  let validator: ExpressionValidator;

  beforeEach(() => {
    validator = new ExpressionValidator();
  });

  for (const { language, adapter, critical = [], high = [], safe = [] } of cases) {
    describe(language, () => {
      const session = createMockDebugSession(language, adapter);

      it.each(critical)('classifies critical operation %s', (expression) => {
        expect(validator.validateExpression(expression, session)).toMatchObject({
          allowed: false,
          riskLevel: 'critical',
        });
      });

      it.each(high)('classifies high-risk operation %s', (expression) => {
        expect(validator.validateExpression(expression, session)).toMatchObject({
          allowed: false,
          riskLevel: 'high',
        });
      });

      it.each(safe)('allows read-only operation %s', (expression) => {
        expect(validator.validateExpression(expression, session).allowed).toBe(true);
      });
    });
  }
});
